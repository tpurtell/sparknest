#!/usr/bin/env bash
# Join an off-grid host (LAN only, ADR-047) to the real cluster.
#
#   scripts/add-offgrid.sh fabric-lan      fabric hosts also listen on the LAN
#                                          (listen = 0.0.0.0:7400; lanes on
#                                          7402); takes effect at their restart
#   scripts/add-offgrid.sh check HOST      root prerequisites on HOST
#   scripts/add-offgrid.sh configure HOST  node.toml, secret and staged unit
#   scripts/add-offgrid.sh join HOST       add it as a learner (from raptor)
#
# HOST is in SPARKNEST_OFFGRID (scripts/cluster.env). Root, once per host
# (printed by `check`): state and mount directories, user_allow_other, the
# system unit, the restart rule, FUSE over io_uring. Install the package
# first: brew install tpurtell/local-ai/sparknest.
set -euo pipefail
cd "$(dirname "$0")/.."
source scripts/cluster.env

CLUSTER=sparknest
STATE=/srv/sparknest
MOUNT=/mnt/sparknest
PORT=7400
API_PORT=7401
BIN=/home/linuxbrew/.linuxbrew/opt/sparknest/bin
SSH=(ssh -F "$HOME/.ssh/config")

offgrid_of() {
  local h name id lanes
  for h in "${SPARKNEST_OFFGRID[@]}"; do
    IFS=: read -r name id lanes <<<"$h"
    if [ "$name" = "$1" ]; then
      echo "$id $lanes"
      return
    fi
  done
  echo "$1 is not in SPARKNEST_OFFGRID (scripts/cluster.env)" >&2
  exit 2
}

fabric_lan() {
  local h host
  for h in "${SPARKNEST_HOSTS[@]}"; do
    IFS=: read -r host _ _ _ <<<"$h"
    "${SSH[@]}" "$host" "sed -i 's/^listen = \"[0-9.]*:$PORT\"/listen = \"0.0.0.0:$PORT\"/' $STATE/node.toml && grep -m1 '^listen' $STATE/node.toml" \
      | sed "s/^/$host: /"
  done
  echo "Takes effect when each fabric host restarts."
}

check() {
  "${SSH[@]}" "$1" bash -s <<CHECK
ok=1
test -d $STATE -a -w $STATE || { echo "missing: $STATE owned by \$(id -un)"; ok=0; }
test -d $MOUNT || { echo "missing: $MOUNT"; ok=0; }
grep -q '^user_allow_other' /etc/fuse.conf || { echo "missing: user_allow_other in /etc/fuse.conf"; ok=0; }
test -f /etc/systemd/system/sparknestd@$CLUSTER.service || { echo "missing: system unit (stage it with configure)"; ok=0; }
[ "\$(cat /sys/module/fuse/parameters/enable_uring 2>/dev/null)" = Y ] || echo "note: fuse.enable_uring is N (falls back to /dev/fuse)"
[ "\$(sysctl -n net.ipv4.tcp_slow_start_after_idle)" = 0 ] || { echo "missing: tcp_slow_start_after_idle=0 (benchmarks/M10-LAN-TCP.md)"; ok=0; }
test -x $BIN/sparknestd || { echo "missing: brew install tpurtell/local-ai/sparknest"; ok=0; }
if [ \$ok = 1 ]; then echo "\$(hostname -s): ready"; else
  echo "Root steps on \$(hostname -s):"
  echo "  sudo install -d -o \$(id -un) -g \$(id -gn) $STATE $MOUNT"
  echo "  grep -q '^user_allow_other' /etc/fuse.conf || echo user_allow_other | sudo tee -a /etc/fuse.conf"
  echo "  sudo cp ~/.config/sparknest/sparknestd@$CLUSTER.service /etc/systemd/system/ && sudo systemctl daemon-reload && sudo systemctl enable sparknestd@$CLUSTER"
  echo "  printf '%s\\n' '# sparknest (benchmarks/M10-LAN-TCP.md): keep the TCP window after idle' 'net.ipv4.tcp_slow_start_after_idle = 0' | sudo tee /etc/sysctl.d/90-sparknest-tcp.conf && sudo sysctl -q --system"
  echo "  sparknest-allow-restart $CLUSTER"
fi
CHECK
}

configure() {
  local host=$1 id lanes members="" h name fid ip user group
  read -r id lanes < <(offgrid_of "$host")
  for h in "${SPARKNEST_HOSTS[@]}"; do
    IFS=: read -r name fid _ _ <<<"$h"
    ip=$(printf '%s\n' "${SPARKNEST_LAN[@]}" | sed -n "s/^$name://p")
    members+="  { id = $fid, name = \"$name\", addr = \"$ip:$PORT\" },"$'\n'
  done
  "${SSH[@]}" "$host" "test -w $STATE && mkdir -p ~/.config/sparknest" \
    || { echo "$host: $STATE missing or not writable (root step; run check)"; exit 1; }
  "${SSH[@]}" "$host" "cat > $STATE/node.toml" <<CFG
# Generated by scripts/add-offgrid.sh: an off-grid host (ADR-047).
[node]
id = $id
name = "$host"
role = "offgrid"
state_dir = "$STATE"
mountpoint = "$MOUNT"
listen = "0.0.0.0:$PORT"
api_listen = "0.0.0.0:$API_PORT"
lanes = $lanes

[cluster]
name = "$CLUSTER"
secret_file = "$STATE/cluster.secret"
# The fabric hosts at their LAN addresses; this host dials them.
members = [
$members]

[fuse]
allow_other = true
io_uring = true

[hf]
home = "/hf-home"
CFG
  # The running cluster's secret, from raptor.
  "${SSH[@]}" raptor "cat $STATE/cluster.secret" \
    | "${SSH[@]}" "$host" "umask 077 && cat > $STATE/cluster.secret"
  user=$("${SSH[@]}" "$host" 'id -un')
  group=$("${SSH[@]}" "$host" 'id -gn')
  sed -e "s#@BIN_DIR@#$BIN#g" -e "s#@STATE_DIR@#$STATE#g" -e "s#@MOUNT@#$MOUNT#g" \
      -e "s#@USER@#$user#g" -e "s#@GROUP@#$group#g" \
    packaging/systemd/sparknestd@.service \
    | "${SSH[@]}" "$host" "cat > ~/.config/sparknest/sparknestd@$CLUSTER.service"
  if "${SSH[@]}" "$host" "$BIN/sparknestd --config $STATE/node.toml --check" >/dev/null; then
    echo "$host: configured (node $id, $lanes lanes)"
  else
    echo "$host: config check FAILED"
  fi
}

join() {
  local host=$1 id
  read -r id _ < <(offgrid_of "$host")
  "${SSH[@]}" raptor "$BIN/nest cluster add $id --offgrid"
  echo "Now start it on $host: sudo systemctl start sparknestd@$CLUSTER"
}

case "${1:-}" in
  fabric-lan) fabric_lan ;;
  check) check "${2:?host}" ;;
  configure) configure "${2:?host}" ;;
  join) join "${2:?host}" ;;
  *) sed -n '2,14p' "$0" >&2; exit 2 ;;
esac
